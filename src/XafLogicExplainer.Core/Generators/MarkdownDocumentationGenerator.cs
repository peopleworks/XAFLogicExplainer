using System.Text;
using System.Text.Json;
using XafLogicExplainer.Core.Interfaces;
using XafLogicExplainer.Core.Models;

namespace XafLogicExplainer.Core.Generators;

/// <summary>
/// Generates markdown and JSON documentation artifacts from extracted project metadata.
/// </summary>
public class MarkdownDocumentationGenerator : IDocumentationGenerator
{
    private readonly DocumentationLabels _l;
    private readonly bool _spanish;

    /// <summary>
    /// Creates a documentation generator for the selected language.
    /// </summary>
    /// <param name="languageCode">Language code used for labels and section captions.</param>
    public MarkdownDocumentationGenerator(string languageCode = "es")
    {
        _l = DocumentationLabels.ForLanguage(languageCode);
        _spanish = languageCode.StartsWith("es", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Picks the wording for the current language.
    /// </summary>
    /// <remarks>
    /// For prose that belongs to one section, where a label on <see cref="DocumentationLabels"/>
    /// would be a caption used once.
    /// </remarks>
    /// <param name="es">Spanish text.</param>
    /// <param name="en">English text.</param>
    private string L(string es, string en) => _spanish ? es : en;

    /// <summary>
    /// Generates a full combined markdown document.
    /// </summary>
    /// <param name="project">Extracted project snapshot.</param>
    /// <returns>Full markdown document.</returns>
    public string GenerateMarkdown(ExtractedProject project)
    {
        var sections = GenerateSections(project);
        var sb = new StringBuilder();

        sb.AppendLine($"# {project.ProjectName} - {_l.FunctionalDocumentation}");
        sb.AppendLine();
        sb.AppendLine($"*Generated: {project.ExtractedAt}*");
        // Only when one was read. `*Framework: *` is a field with nothing in it, which reads as
        // a broken document rather than as the honest "this was not declared".
        if (!string.IsNullOrWhiteSpace(project.TargetFramework))
            sb.AppendLine($"*Framework: {project.TargetFramework}*");
        sb.AppendLine();

        foreach (var section in sections)
        {
            sb.AppendLine(section.Content);
            sb.AppendLine();
            sb.AppendLine("---");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    /// <summary>
    /// Serializes project extraction output as JSON.
    /// </summary>
    /// <param name="project">Extracted project snapshot.</param>
    /// <returns>JSON representation of the project.</returns>
    public string GenerateJson(ExtractedProject project)
    {
        return JsonSerializer.Serialize(project, JsonOptions);
    }

    /// <summary>
    /// Deserializes an extracted project from JSON.
    /// </summary>
    /// <param name="json">JSON payload generated by this toolchain.</param>
    /// <returns>Deserialized project model or null when payload is invalid.</returns>
    public static ExtractedProject? DeserializeProject(string json)
    {
        return JsonSerializer.Deserialize<ExtractedProject>(json, JsonOptions);
    }

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    /// <summary>
    /// Generates all standalone documentation sections for upload or local export.
    /// </summary>
    /// <param name="project">Extracted project snapshot.</param>
    /// <returns>List of generated sections.</returns>
    public List<DocumentSection> GenerateSections(ExtractedProject project)
    {
        var sections = new List<DocumentSection>
        {
            GenerateOverviewSection(project),
            GenerateEntitiesSection(project),
            GenerateControllersSection(project),
            GenerateBusinessRulesSection(project),
            GenerateConfigurationSection(project),
            GenerateNavigationSection(project),
        };

        if (project.ModelEditorInfo != null)
            sections.Add(GenerateModelEditorSection(project));

        if (project.Views.Count > 0)
            sections.Add(GenerateScreensSection(project));

        // Only when the application has something to say about reports. One that never registered
        // ReportsModuleV2 and ships no layouts gets no section rather than an empty one — "no
        // reports" is worth printing when it is a finding, not when it is the default.
        if (project.ReferencesReportsModule
            || project.Reports.Count > 0
            || project.UnregisteredReportLayouts.Count > 0)
        {
            sections.Add(GenerateReportsSection(project));
        }

        return sections;
    }

    /// <summary>
    /// The reports an application declares, and what the repository cannot show.
    /// </summary>
    /// <remarks>
    /// The sentence under the heading does more work than the list. Reports V2 lets users build
    /// reports at run time in the End-User Designer, and those are stored as rows rather than
    /// files, so an extraction that reads source can never see them. An application with forty
    /// user-designed reports and none in its repository is the ordinary case rather than an exotic
    /// one — checked against a production application where <c>ReportsModuleV2</c> is registered,
    /// the store mode is the database, and the source contains no report at all.
    /// <para>
    /// Printing "no reports" there would not be an incomplete answer but a wrong one, and the more
    /// use an application makes of reports the wronger it would get.
    /// </para>
    /// </remarks>
    private DocumentSection GenerateReportsSection(ExtractedProject project)
    {
        var sb = new StringBuilder();

        sb.AppendLine($"## {L("Reportes", "Reports")}");
        sb.AppendLine();
        sb.AppendLine(ReportsPreamble(project));
        sb.AppendLine();

        // One layout can carry several registrations — the same `.repx` offered both from the
        // navigation and in place on a list view is an ordinary pair. Rendering the filter, the
        // bindings and the whole of `GetCriteria()` again under the second one buries the
        // difference between them, which is the only thing a reader opened it for.
        var alreadyShown = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var report in project.Reports)
            AppendReport(sb, project, report, alreadyShown);

        AppendUnregisteredReports(sb, project);

        return new DocumentSection
        {
            Title = L("Reportes", "Reports"),
            Content = sb.ToString().TrimEnd(),
        };
    }

    /// <summary>
    /// What the list of reports is: all of them, a lower bound, or an absence worth explaining.
    /// </summary>
    private string ReportsPreamble(ExtractedProject project)
    {
        if (!project.ReferencesReportsModule)
        {
            return L(
                $"Se leyeron {project.Reports.Count} reportes del codigo. Esta aplicacion no registra "
                + "`ReportsModuleV2`, asi que estos son todos los que hay.",
                $"{project.Reports.Count} reports read from source. This application does not register "
                + "`ReportsModuleV2`, so these are all of them.");
        }

        if (project.Reports.Count == 0)
        {
            return L(
                "Esta aplicacion registra `ReportsModuleV2` y **no declara ningun reporte en el "
                + "codigo**. Eso casi nunca significa que no tenga reportes: con ese modulo, los "
                + "usuarios los disenan en tiempo de ejecucion y quedan guardados como filas en la "
                + "base de datos. Leer el repositorio no puede mostrarlos, y el numero real no es "
                + "cero sino desconocido.",
                "This application registers `ReportsModuleV2` and **declares no reports in source**. "
                + "That rarely means it has none: with that module in, users design reports at run "
                + "time and they are stored as rows in the database. Reading the repository cannot "
                + "show them, and the true number is not zero but unknown.");
        }

        return L(
            $"Se leyeron {project.Reports.Count} reportes del codigo. Esta aplicacion tambien registra "
            + "`ReportsModuleV2`, con lo que los usuarios pueden crear los suyos en tiempo de "
            + "ejecucion; esos viven en la base de datos, asi que **esta lista es una cota inferior**.",
            $"{project.Reports.Count} reports read from source. This application also registers "
            + "`ReportsModuleV2`, so users can build their own at run time; those live in the "
            + "database, which makes **this list a lower bound**.");
    }

    private void AppendReport(
        StringBuilder sb, ExtractedProject project, ExtractedReport report,
        Dictionary<string, string> alreadyShown)
    {
        sb.AppendLine($"### {report.DisplayName}");
        sb.AppendLine();
        sb.AppendLine($"- **{L("Sobre", "Over")}:** `{report.DataType}`");
        sb.AppendLine($"- **{L("Clase del reporte", "Report class")}:** `{report.ReportType}`");

        if (report.ParametersType is { Length: > 0 } parameters)
            sb.AppendLine($"- **{L("Dialogo previo", "Opens with")}:** `{parameters}`");

        // Null is not false. The registration overload that says nothing about in-place reporting
        // leaves XAF's own default in charge, and reporting "no" there would be an invention.
        if (report.IsInplaceReport is { } inplace)
        {
            sb.AppendLine($"- **{L("En la lista del objeto", "Offered in place")}:** "
                + (inplace ? L("si", "yes") : L("no", "no")));
        }

        var registeredAt = SourceCitation.Of(project, report.FilePath, report.Line);

        if (registeredAt.Length > 0)
            sb.AppendLine($"- **{L("Registrado en", "Registered at")}:** {registeredAt}");

        sb.AppendLine();

        // Keyed by what is actually shared. Two registrations of one `.repx` differ in their
        // options, which are printed above, and in nothing below.
        var key = $"{report.Layout?.FilePath}|{report.Layout?.Line}|{report.ParametersObject?.ClassName}";

        if (report.Layout is not null || report.ParametersObject is not null)
        {
            if (alreadyShown.TryGetValue(key, out var shownUnder))
            {
                sb.AppendLine(L(
                    $"Mismo diseno y dialogo que **{shownUnder}**, arriba.",
                    $"Same layout and dialog as **{shownUnder}**, above."));
                sb.AppendLine();

                return;
            }

            alreadyShown[key] = report.DisplayName;
        }

        AppendLayout(sb, project, report.Layout);
        AppendParametersObject(sb, project, report.ParametersObject);
    }

    /// <summary>
    /// What a report shows: the decisions in its layout, not its appearance.
    /// </summary>
    private void AppendLayout(StringBuilder sb, ExtractedProject project, ReportLayout? layout)
    {
        if (layout is null)
            return;

        var at = SourceCitation.Of(project, layout.FilePath, layout.Line);

        sb.AppendLine($"{L("Diseno leido de", "Layout read from")} {LayoutSource(layout.Source)}"
            + (at.Length > 0 ? $", {at}" : "") + ".");
        sb.AppendLine();

        if (layout.DataSource is { Length: > 0 } source)
        {
            var member = layout.DataMember is { Length: > 0 } dataMember ? $" / `{dataMember}`" : "";
            sb.AppendLine($"- **{L("Origen de datos", "Data source")}:** `{source}`{member}");
        }

        // The filter is the most consequential line in a report and the one nothing else in the
        // repository mentions: "approved only", "this fiscal year", "excluding cancelled".
        if (layout.FilterString is { Length: > 0 } filter)
            sb.AppendLine($"- **{L("Filtra por", "Filters on")}:** `{filter}`");

        if (layout.GroupFields.Count > 0)
        {
            sb.AppendLine($"- **{L("Agrupa por", "Grouped by")}:** "
                + string.Join(", ", layout.GroupFields.Select(field => $"`{field}`")));
        }

        if (layout.CalculatedFields.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine($"**{L("Campos calculados", "Calculated fields")}**");
            sb.AppendLine();
            sb.AppendLine($"| {L("Nombre", "Name")} | {L("Expresion", "Expression")} |");
            sb.AppendLine("| --- | --- |");

            foreach (var field in layout.CalculatedFields)
                sb.AppendLine($"| `{field.Name}` | `{field.Expression}` |");
        }

        if (layout.Bindings.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine($"**{L("Expresiones en el diseno", "Expressions in the layout")}**");
            sb.AppendLine();
            sb.AppendLine($"| {L("Control", "Control")} | {L("Propiedad", "Property")} | "
                + $"{L("Expresion", "Expression")} |");
            sb.AppendLine("| --- | --- | --- |");

            foreach (var binding in layout.Bindings)
                sb.AppendLine($"| `{binding.Control}` | `{binding.Property}` | `{binding.Expression}` |");
        }

        sb.AppendLine();
    }

    private void AppendParametersObject(
        StringBuilder sb, ExtractedProject project, ReportParametersObject? parameters)
    {
        if (parameters is null)
            return;

        var at = SourceCitation.Of(project, parameters.FilePath, parameters.Line);

        sb.AppendLine($"**{L("El dialogo pide", "The dialog asks for")}** — `{parameters.ClassName}`"
            + (at.Length > 0 ? $", {at}" : "") + ".");
        sb.AppendLine();

        if (parameters.Fields.Count > 0)
        {
            sb.AppendLine($"| {L("Campo", "Field")} | {L("Tipo", "Type")} | "
                + $"{L("Por defecto", "Default")} |");
            sb.AppendLine("| --- | --- | --- |");

            foreach (var field in parameters.Fields)
            {
                var fallback = field.Default is { Length: > 0 } value ? $"`{value}`" : "";
                sb.AppendLine($"| `{field.Name}` | `{field.Type}` | {fallback} |");
            }

            sb.AppendLine();
        }

        // What the answers are turned into. This is the business logic of the dialog, and the
        // reason the parameters object is worth reading rather than merely naming.
        if (parameters.CriteriaSource is { Length: > 0 } criteria)
        {
            sb.AppendLine(L("Con esas respuestas filtra", "Those answers become the filter") + ":");
            sb.AppendLine();
            sb.AppendLine("```csharp");
            sb.AppendLine(criteria.Trim());
            sb.AppendLine("```");
            sb.AppendLine();
        }

        if (parameters.SortingSource is { Length: > 0 } sorting)
        {
            sb.AppendLine(L("Y el orden", "And the sort order") + ":");
            sb.AppendLine();
            sb.AppendLine("```csharp");
            sb.AppendLine(sorting.Trim());
            sb.AppendLine("```");
            sb.AppendLine();
        }
    }

    /// <summary>
    /// Layouts and dialogs that exist in the repository and that nothing registers.
    /// </summary>
    /// <remarks>
    /// A shop that designs reports outside Visual Studio keeps the exports beside the module and
    /// imports them into the database by hand, so these files are real work that no registration
    /// claims. Listing them as unregistered is the difference between "this exists and nothing in
    /// the code points at it" and silence.
    /// </remarks>
    private void AppendUnregisteredReports(StringBuilder sb, ExtractedProject project)
    {
        if (project.UnregisteredReportLayouts.Count == 0
            && project.UnregisteredReportParameters.Count == 0)
        {
            return;
        }

        sb.AppendLine($"### {L("Disenos que nadie registra", "Layouts nothing registers")}");
        sb.AppendLine();
        sb.AppendLine(L(
            "Estos archivos estan en el repositorio y ninguna llamada de registro los nombra. "
            + "Normalmente son disenos exportados de la aplicacion e importados a mano a la base "
            + "de datos, asi que son trabajo real que el codigo no menciona.",
            "These files are in the repository and no registration call names them. Usually they "
            + "are layouts exported from the running application and imported into the database by "
            + "hand — real work that the code never mentions."));
        sb.AppendLine();

        foreach (var layout in project.UnregisteredReportLayouts)
        {
            var at = SourceCitation.Of(project, layout.FilePath, layout.Line);
            var filter = layout.FilterString is { Length: > 0 } criteria
                ? $" — {L("filtra por", "filters on")} `{criteria}`"
                : "";

            sb.AppendLine($"- {at}{filter}");
        }

        foreach (var parameters in project.UnregisteredReportParameters)
        {
            var at = SourceCitation.Of(project, parameters.FilePath, parameters.Line);

            sb.AppendLine($"- `{parameters.ClassName}` — "
                + L("dialogo de parametros que ningun reporte nombra",
                    "a parameters dialog no report names")
                + (at.Length > 0 ? $", {at}" : ""));
        }

        sb.AppendLine();
    }

    private string LayoutSource(ReportLayoutSource source) => source switch
    {
        ReportLayoutSource.DesignerCode => L("el codigo del disenador", "designer code"),
        ReportLayoutSource.Repx => L("un archivo `.repx`", "a `.repx` file"),
        _ => L("el codigo del reporte", "the report's own code"),
    };

    /// <summary>Says which class a folded declaration came from, for a line that has room.</summary>
    private string Declarer(string? inheritedFrom)
        => inheritedFrom is { Length: > 0 } ? $" — {Inherited(inheritedFrom)}" : "";

    /// <summary>Says which class a folded declaration came from, for a cell that has none.</summary>
    private string Inherited(string declarer) => $"{L("heredado de", "inherited from")} `{declarer}`";

    /// <summary>
    /// Names a validation rule the way the rest of the application does, when it was named.
    /// </summary>
    /// <remarks>
    /// The identifier is what a validation error carries and what the Model Editor lists it under,
    /// so it is how a reader gets from this line back to the thing itself.
    /// <para>
    /// The contexts are shown only when they are not the ordinary save, because on the ordinary
    /// save they are true of nearly every rule and say nothing. When they are anything else they
    /// are the whole story: the rule does not run where a reader would assume it does.
    /// </para>
    /// </remarks>
    private string RuleName(ExtractedValidationRule rule)
    {
        var id = rule.Id is { Length: > 0 } ? $" `{rule.Id}`" : "";

        var unusualContext = rule.Contexts is { Length: > 0 } contexts
                             && contexts is not ("DefaultContexts.Save" or "Save");

        return unusualContext ? $"{id} ({L("contexto", "context")} `{rule.Contexts}`)" : id;
    }

    /// <summary>
    /// Says what a validation rule enforces and what the user is told when it fires.
    /// </summary>
    /// <remarks>
    /// This printed the attribute's raw arguments — <c>arg0=Sale_TotalNotNegative,
    /// arg1=DefaultContexts.Save</c> — because those were the only fields the reader of an
    /// attribute filled in. Anything still unrecognised is kept, by value: dropping it would trade
    /// one unreadable rendering for a silently incomplete one, and <c>RuleRange</c>'s bounds are
    /// exactly the kind of argument that lives there.
    /// </remarks>
    private string DescribeRule(ExtractedValidationRule rule)
    {
        var known = new[] { rule.Id, rule.Contexts, rule.Expression, rule.MessageTemplate, rule.TargetCriteria };
        var parts = new List<string>();

        if (rule.Expression is { Length: > 0 }) parts.Add($"`{rule.Expression}`");

        parts.AddRange(rule.Parameters
            .Where(p => !known.Contains(p.Value, StringComparer.Ordinal))
            .Select(p => p.Key.StartsWith("arg", StringComparison.Ordinal) ? p.Value : $"{p.Key}={p.Value}"));

        if (rule.MessageTemplate is { Length: > 0 }) parts.Add($"“{rule.MessageTemplate}”");
        if (rule.TargetCriteria is { Length: > 0 }) parts.Add($"{_l.When} `{rule.TargetCriteria}`");

        // Empty rather than "no arguments": a [RuleRequiredField] whose id and contexts are
        // already on the line has nothing further to say, and saying so reads as a gap.
        return parts.Count > 0 ? $": {string.Join(" — ", parts)}" : "";
    }

    /// <summary>
    /// Opens an appearance rule's line: what it is called, and what activates it.
    /// </summary>
    /// <remarks>
    /// Both halves are optional in real code, and both were printed as though they were not.
    /// <para>
    /// A rule written on a property needs no identifier — the property already says what it governs
    /// — and the DevExpress non-persistent-objects demo writes <c>[Appearance("", Enabled = false)]</c>
    /// at class level. The empty name rendered as <c>****</c>.
    /// </para>
    /// <para>
    /// A rule with no criteria is not a rule whose condition went missing: in XAF it is
    /// <em>always</em> active, which is the stronger of the two claims and the one a reader most
    /// needs. It rendered as <c>when ``</c> — a condition that looks like it failed to load.
    /// <see cref="HtmlExplainerGenerator"/> had already settled on the right word.
    /// </para>
    /// </remarks>
    private string OpenAppearance(ExtractedAppearanceRule rule)
    {
        var condition = rule.Criteria is { Length: > 0 } criteria ? $"{_l.When} `{criteria}`" : _l.Always;

        // No identifier leaves nothing to put in front of the condition, and an empty bold span is
        // worse than none: DescribeAppearance names the targets, which is what identifies it.
        return rule.Id is { Length: > 0 } id ? $"**{id}** — {condition}" : condition;
    }

    /// <summary>
    /// Says what an appearance rule actually does, and on which screen.
    /// </summary>
    /// <remarks>
    /// It used to print the visibility and the enabled flag only, so a rule whose whole effect is
    /// a red font read as "when OnHand = 0 ()" — a condition with no consequence, on no stated
    /// screen. The context matters as much: the same criteria colours a list and does nothing in a
    /// detail view.
    /// </remarks>
    private string DescribeAppearance(ExtractedAppearanceRule rule)
    {
        var effects = new List<string>();

        if (rule.Visibility is { Length: > 0 }) effects.Add($"{_l.Visibility}={rule.Visibility}");
        if (rule.Enabled is { Length: > 0 }) effects.Add($"{_l.Enabled}={rule.Enabled}");
        if (rule.FontColor is { Length: > 0 }) effects.Add($"{L("color de letra", "font colour")}={rule.FontColor}");
        if (rule.BackColor is { Length: > 0 }) effects.Add($"{L("color de fondo", "back colour")}={rule.BackColor}");

        var where = new List<string>();

        if (rule.Context is { Length: > 0 }) where.Add($"{L("en", "in")} {rule.Context}");
        if (rule.TargetItems is { Length: > 0 }) where.Add($"{TargetKind(rule)}: {rule.TargetItems}");

        var text = effects.Count > 0 ? $": {string.Join(", ", effects)}" : $": {L("sin efecto declarado", "no declared effect")}";

        return where.Count > 0 ? $"{text} ({string.Join(", ", where)})" : text;
    }

    /// <summary>
    /// What kind of thing the rule's targets are.
    /// </summary>
    /// <remarks>
    /// Every target used to be called a field, so a rule disabling the <c>Delete</c> action read as
    /// governing a column called Delete — a column no reader would find, described confidently. XAF
    /// defaults the type to <c>ViewItem</c>, so an absent one is a field and the common case is
    /// unchanged.
    /// </remarks>
    private string TargetKind(ExtractedAppearanceRule rule) => rule.AppearanceItemType switch
    {
        "Action" => L("acciones", "actions"),
        "LayoutItem" => L("elementos de layout", "layout items"),
        _ => _l.Fields,
    };

    /// <summary>Joins controller names for a one-line mention.</summary>
    private static string Names(IEnumerable<ViewActivation> activations) =>
        string.Join(", ", activations
            .OrderBy(a => a.Controller, StringComparer.Ordinal)
            .Select(a => $"`{a.Controller}`"));

    /// <summary>
    /// Says in one phrase what kind of view this is, where it appears, and where it came from.
    /// </summary>
    /// <remarks>
    /// Written out rather than printed as three enum names, which would leave English words inside
    /// the Spanish document. The view class names stay as they are: <c>DetailView</c> is what XAF
    /// calls it, in either language.
    /// </remarks>
    private string DescribeView(ExtractedView view)
    {
        var kind = view.ViewType switch
        {
            ModelViewType.ListView when view.Id.EndsWith("_LookupListView", StringComparison.Ordinal) =>
                L("Vista de busqueda", "Lookup list view"),
            ModelViewType.ListView => L("Vista de lista", "List view"),
            ModelViewType.DetailView => L("Vista de detalle", "Detail view"),
            _ => L("Dashboard", "Dashboard"),
        };

        var where = view.Nesting switch
        {
            ViewNesting.Root => L("raiz", "root"),
            ViewNesting.Nested => L("anidada", "nested"),
            _ => L("raiz o anidada", "root or nested"),
        };

        var origin = view.Origin switch
        {
            ViewOrigin.Generated => L("generada por XAF, no existe en ningun archivo",
                                      "generated by XAF, exists in no file"),
            ViewOrigin.Customized => L("generada por XAF y personalizada en el Model Editor",
                                       "generated by XAF and customized in the Model Editor"),
            _ => L("definida en el Model Editor", "defined in the Model Editor"),
        };

        return $"{kind}, {where}, {origin}";
    }

    /// <summary>
    /// Generates the screen inventory: every view, and what XAF loads onto it.
    /// </summary>
    /// <remarks>
    /// Kept out of the always-loaded index on purpose — an application of any size has hundreds of
    /// views, and this is the file to open when the question is about one screen.
    /// </remarks>
    private DocumentSection GenerateScreensSection(ExtractedProject project)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# {project.ProjectName} - {_l.Screens}");
        sb.AppendLine();
        sb.AppendLine(L(
            $"{project.Views.Count} vistas. XAF genera una vista de lista, una de detalle y una de busqueda " +
            "por cada clase de negocio, mas una lista por cada coleccion, asi que la mayoria no existe en " +
            "ningun archivo: buscarlas en el codigo no encuentra nada, y eso no significa que falten.",
            $"{project.Views.Count} views. XAF generates a list, a detail and a lookup view for every " +
            "business class, plus a list view for every collection, so most of these exist in no file: " +
            "searching the source tree for one finds nothing, and that is not evidence it is missing."));

        foreach (var group in project.Views
                     .GroupBy(v => v.ObjectType ?? "-")
                     .OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.AppendLine();
            sb.AppendLine($"## {group.Key}");
            sb.AppendLine();

            foreach (var view in group.OrderBy(v => v.Id, StringComparer.Ordinal))
            {
                sb.AppendLine($"### {view.Id}");
                sb.AppendLine();
                sb.AppendLine($"- {DescribeView(view)}");

                if (view.InNavigation)
                    sb.AppendLine(L("- Abierta desde la navegacion", "- Opened from navigation"));

                if (view.OwnerProperty is { } ownerProperty)
                    sb.AppendLine($"- {L("Mostrada por", "Shown by")} `{view.OwnerEntity}.{ownerProperty}`");

