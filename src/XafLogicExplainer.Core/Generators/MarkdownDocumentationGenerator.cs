            if (model.Options.RequiredFieldMark != null) sb.AppendLine($"- **{_l.RequiredFieldMark}:** {model.Options.RequiredFieldMark}");
            sb.AppendLine();
        }

        if (model.BOModelClasses.Count > 0)
        {
            sb.AppendLine($"## {_l.BOModelCustomizations}");
            sb.AppendLine();
            sb.AppendLine($"| {_l.Class} | {_l.Caption} | {_l.Cloneable} | {_l.Other} |");
            sb.AppendLine("|-------|---------|----------|-------|");
            foreach (var cls in model.BOModelClasses)
            {
                var others = cls.CustomAttributes.Count > 0
                    ? string.Join(", ", cls.CustomAttributes.Select(kv => $"{kv.Key}={kv.Value}"))
                    : "";
                sb.AppendLine($"| `{cls.ClassName}` | {cls.Caption ?? ""} | {(cls.IsCloneable ? _l.Yes : "")} | {others} |");
            }
            sb.AppendLine();
        }

        if (model.Views.Count > 0)
        {
            sb.AppendLine($"## {_l.ViewCustomizations}");
            sb.AppendLine();
            foreach (var view in model.Views)
            {
                sb.AppendLine($"### {view.Id} ({view.ViewType})");
                sb.AppendLine();
                if (view.Caption != null) sb.AppendLine($"- **{_l.Caption}:** {view.Caption}");
                if (view.AllowEdit.HasValue) sb.AppendLine($"- **{_l.Editable}:** {(view.AllowEdit.Value ? _l.Yes : _l.No)}");
                if (view.AllowDelete.HasValue) sb.AppendLine($"- **{_l.AllowDelete}:** {(view.AllowDelete.Value ? _l.Yes : _l.No)}");
                if (view.AllowNew.HasValue) sb.AppendLine($"- **{_l.AllowCreate}:** {(view.AllowNew.Value ? _l.Yes : _l.No)}");
                if (view.Criteria != null) sb.AppendLine($"- **{_l.FilterCriteria}:** `{view.Criteria}`");
                if (view.EditorTypeName != null) sb.AppendLine($"- **{_l.CustomEditor}:** `{view.EditorTypeName}`");

                if (view.Columns.Count > 0)
                {
                    sb.AppendLine();
                    sb.AppendLine($"**{_l.ConfiguredColumns}:**");
                    sb.AppendLine();
                    sb.AppendLine($"| {_l.Property} | {_l.Order} | {_l.Width} | {_l.Sorting} | {_l.Caption} |");
                    sb.AppendLine("|-----------|-------|-------|-------------|---------|");
                    foreach (var col in view.Columns.OrderBy(c => c.Index ?? 999))
                    {
                        sb.AppendLine($"| `{col.PropertyName ?? col.Id}` | {col.Index?.ToString() ?? ""} | {col.Width?.ToString() ?? ""} | {col.SortOrder ?? ""} | {col.Caption ?? ""} |");
                    }
                    sb.AppendLine();
                }

                if (view.Filters.Count > 0)
                {
                    sb.AppendLine($"**{_l.PredefinedFilters}:**");
                    sb.AppendLine();
                    foreach (var filter in view.Filters)
                    {
                        sb.AppendLine($"- **{filter.Caption ?? filter.Id}**: `{filter.Criteria}`");
                    }
                    sb.AppendLine();
                }
            }
        }

        if (model.NavigationItems != null && model.NavigationItems.Groups.Count > 0)
        {
            sb.AppendLine($"## {_l.NavigationModelEditor}");
            sb.AppendLine();
            if (model.NavigationItems.NavigationStyle != null)
                sb.AppendLine($"- **{_l.Style}:** {model.NavigationItems.NavigationStyle}");
            if (model.NavigationItems.StartupNavigationItem != null)
                sb.AppendLine($"- **{_l.StartupView}:** {model.NavigationItems.StartupNavigationItem}");
            sb.AppendLine();

            foreach (var group in model.NavigationItems.Groups)
            {
                sb.AppendLine($"### {group.Caption ?? group.Id}");
                foreach (var item in group.Items.OrderBy(i => i.Index ?? 999))
                {
                    var icon = item.ImageName != null ? $" ({_l.Icon}: {item.ImageName})" : "";
                    var viewRef = item.ViewId != null ? $" -> `{item.ViewId}`" : "";
                    sb.AppendLine($"- **{item.Caption ?? item.Id}**{viewRef}{icon}");
                }
                sb.AppendLine();
            }
        }

        if (model.SchemaModules.Count > 0)
        {
            sb.AppendLine($"## {_l.RegisteredSchemaModules}");
            sb.AppendLine();
            foreach (var mod in model.SchemaModules)
            {
                sb.AppendLine($"- **{mod.Name}** v{mod.Version}");
            }
            sb.AppendLine();
        }

        sb.AppendLine($"## {_l.ProcessedXafmlFiles}");
        sb.AppendLine();
        foreach (var f in model.SourceFiles)
        {
            sb.AppendLine($"- `{Path.GetFileName(f)}` ({Path.GetDirectoryName(f)})");
        }

        return new DocumentSection
        {
            Title = _l.ModelEditorCustomizations,
            FileName = $"{project.ProjectName}_ModelEditor",
            Content = sb.ToString(),
            Description = string.Format(_l.ModelEditorDescription, project.ProjectName),
            Tags = "model-editor,xafml,views,columns,filters,ui-customization"
        };
    }
